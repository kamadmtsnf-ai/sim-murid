import { readFile, writeFile } from 'node:fs/promises';
import { createIsolatedDatabase, projectRoot } from './harness.mjs';

const {db,migrations}=await createIsolatedDatabase();
try {
  const columns=(await db.query(`select table_name,column_name,data_type,udt_name,is_nullable,column_default,is_generated,ordinal_position from information_schema.columns where table_schema='public' order by table_name,ordinal_position`)).rows;
  const foreignKeys=(await db.query(`
    select src.relname table_name,con.conname foreign_key_name,dst.relname referenced_relation,
    (select jsonb_agg(a.attname order by u.ord) from unnest(con.conkey) with ordinality u(num,ord) join pg_attribute a on a.attrelid=con.conrelid and a.attnum=u.num) columns,
    (select jsonb_agg(a.attname order by u.ord) from unnest(con.confkey) with ordinality u(num,ord) join pg_attribute a on a.attrelid=con.confrelid and a.attnum=u.num) referenced_columns,
    exists(select 1 from pg_constraint uq where uq.conrelid=con.conrelid and uq.contype in ('p','u') and uq.conkey=con.conkey) is_one_to_one
    from pg_constraint con join pg_class src on src.oid=con.conrelid join pg_namespace ns on ns.oid=src.relnamespace
    join pg_class dst on dst.oid=con.confrelid join pg_namespace nd on nd.oid=dst.relnamespace
    where con.contype='f' and ns.nspname='public' and nd.nspname='public' order by src.relname,con.conname
  `)).rows;
  let source='/** Generated by LOCAL PGlite introspection, not Supabase cloud gen types.\n * Regenerate from the selected Supabase target before live API integration.\n * Command: npm run db:types\n */\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\n\nexport type Database = {\n  public: {\n    Tables: {\n';
  const tables=[...new Set(columns.map((column)=>column.table_name))];
  const tsType=(column)=>{
    if(['json','jsonb'].includes(column.udt_name))return 'Json';
    if(column.udt_name==='bool')return 'boolean';
    if(['int2','int4','int8','float4','float8','numeric'].includes(column.udt_name))return 'number';
    const strings=['uuid','text','varchar','bpchar','date','timestamp','timestamptz','time','timetz'];
    if(strings.includes(column.udt_name))return 'string';
    throw Error(`Unmapped PostgreSQL type ${column.udt_name}`);
  };
  for(const table of tables){
    const cols=columns.filter((column)=>column.table_name===table);
    source+=`      ${table}: {\n`;
    for(const mode of ['Row','Insert','Update']){
      source+=`        ${mode}: {\n`;
      for(const c of cols){
        const generated=c.is_generated!=='NEVER';
        const optional=mode!=='Row'&&(mode==='Update'||generated||c.column_default!==null||c.is_nullable==='YES');
        const type=mode!=='Row'&&generated?'never':tsType(c)+(c.is_nullable==='YES'?' | null':'');
        source+=`          ${c.column_name}${optional?'?':''}: ${type};\n`;
      }
      source+='        };\n';
    }
    const rels=foreignKeys.filter((fk)=>fk.table_name===table).map((fk)=>({foreignKeyName:fk.foreign_key_name,columns:fk.columns,isOneToOne:fk.is_one_to_one,referencedRelation:fk.referenced_relation,referencedColumns:fk.referenced_columns}));
    source+=`        Relationships: ${JSON.stringify(rels)};\n      };\n`;
  }
  source+='    };\n    Views: Record<never, never>;\n    Functions: Record<never, never>;\n    Enums: Record<never, never>;\n    CompositeTypes: Record<never, never>;\n  };\n};\n\nexport type TableRow<Name extends keyof Database["public"]["Tables"]> = Database["public"]["Tables"][Name]["Row"];\n';
  const path=`${projectRoot}src/lib/supabase/database.types.ts`;
  if(process.argv.includes('--check')){
    if(await readFile(path,'utf8')!==source)throw Error('Database type snapshot drift; run npm run db:types');
    console.log(`PASS: ${tables.length} public table types match fresh migration replay.`);
  }else{
    await writeFile(path,source);
    console.log(`Generated local introspection types for ${tables.length} public tables; cloud types still pending.`);
  }
  const guards=(await db.query(`select n.nspname schema_name,c.relname table_name,c.relrowsecurity rls_enabled from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname in ('public','sim_murid_private') and c.relkind='r' order by n.nspname,c.relname`)).rows;
  const snapshot={source:'isolated PGlite PostgreSQL introspection, not remote Supabase',migrations,tables:guards,publicColumns:columns,publicForeignKeys:foreignKeys};
  if(!process.argv.includes('--check'))await writeFile(`${projectRoot}docs/database/schema-snapshot.json`,JSON.stringify(snapshot,null,2)+'\n');
} finally {await db.close();}
